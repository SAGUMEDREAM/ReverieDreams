    private static void addRole(TranslationBuilder builder, NPCRoleType role, String name, String eggSuffix) {
        builder.add(role.getEntityType().value(), name);
        // Previously converted companions may have saved this translation key as their name.
        if (!role.isCustom() && !BuiltInRegistries.ENTITY_TYPE.containsKey(role.getId())) {
            builder.add(Util.makeDescriptionId("entity", role.getId()), name);
        }
        builder.add(role.getEgg().asItem(), name + eggSuffix);
    }

    private static void addEntity(TranslationBuilder builder, RegistrySupplier<? extends EntityType<?>> entity, String name, String eggName) {
        builder.add(entity.value(), name);
        var egg = RDEntityTypes.SPAWN_EGG_BIND.get(entity);
        if (egg != null)
            builder.add(egg.asItem(), eggName);
    }
