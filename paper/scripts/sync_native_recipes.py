"""Export additional source recipes whose item dependencies already exist in the CE pack.

Unsupported types, custom tags and result component transformations remain explicit gaps.
No Mod files are modified. Requires PyYAML.
"""
import argparse
from collections import Counter
import json
from pathlib import Path

import yaml


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    root = args.root.resolve()
    configuration = root / "paper/src/main/craftengine/reverie_dreams/configuration"
    target = configuration / "standard-extra.yml"
    items, recipes = set(), set()
    for path in sorted(configuration.glob("*.yml")):
        if path == target:
            continue
        content = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        items.update(content.get("items", {}))
        recipes.update(content.get("recipes", {}))
    exported, pending = {}, []

    def check_ingredient(value):
        if not isinstance(value, str):
            raise ValueError("ingredient components/alternatives require an explicit adapter")
        if value.startswith(("minecraft:", "#minecraft:")) or value in items:
            return value
        raise ValueError("unresolved ingredient " + value)

    directory = root / "common/src/generated/resources/data/reverie_dreams/recipe"
    for path in sorted(directory.glob("*.json")):
        recipe_id = "reverie_dreams:" + path.stem
        if recipe_id in recipes:
            continue
        source = json.loads(path.read_text(encoding="utf-8"))
        try:
            kind = source["type"].split(":", 1)[-1]
            if kind.startswith("crafting_"):
                kind = kind[len("crafting_"):]
            if kind not in {"shaped", "shapeless", "smelting", "blasting", "smoking", "campfire_cooking", "stonecutting"}:
                raise ValueError("unsupported type " + source["type"])
            result = source["result"]
            if not isinstance(result, dict) or result.get("components"):
                raise ValueError("result components require an explicit adapter")
            check_ingredient(result["id"])
            recipe = {"type": kind}
            if kind == "shaped":
                recipe.update(pattern=source["pattern"], ingredients={k: check_ingredient(v) for k, v in source["key"].items()})
            elif kind == "shapeless":
                recipe["ingredients"] = [check_ingredient(v) for v in source["ingredients"]]
            elif kind == "stonecutting":
                recipe["ingredients"] = check_ingredient(source["ingredient"])
            else:
                recipe.update(ingredient=check_ingredient(source["ingredient"]), time=source["cookingtime"], experience=source["experience"])
            if "group" in source:
                recipe["group"] = source["group"]
            recipe["result"] = {"id": result["id"], "count": result.get("count", 1)}
            exported[recipe_id] = recipe
        except (ValueError, KeyError) as failure:
            pending.append({"id": recipe_id, "source": path.relative_to(root).as_posix(), "reason": str(failure)})
    target.write_text("# Generated by paper/scripts/sync_native_recipes.py from unmodified Mod JSON.\n" +
                      yaml.safe_dump({"recipes": exported}, sort_keys=False, allow_unicode=True), encoding="utf-8")
    source_ids = {"reverie_dreams:" + path.stem for path in directory.glob("*.json")}
    report = {"sourceRecipeFiles": len(source_ids), "existingRecipes": len(recipes),
              "sourceRecipesCovered": len(recipes.intersection(source_ids)) + len(exported),
              "compatibilityRecipes": sum(key.startswith("reverie_dreams:compat/") for key in recipes),
              "dynamicNativeRecipes": sum(key.startswith("reverie_dreams:danmaku_dye/") for key in recipes),
              "additionalRecipes": len(exported), "pending": pending,
              "additionalTypes": dict(Counter(value["type"] for value in exported.values()))}
    (root / "migration/native-recipe-coverage.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    summary = {key: value for key, value in report.items() if key != "pending"}
    summary["pending"] = len(pending)
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
